#!/usr/bin/env node
// Writes global-income-tax-calculator/labels-id.js: the Indonesian for every piece of text the
// engine writes (line labels, bracket adjustments, notes, reasons, the tax year and place),
// for the calculator's Indonesian page (id/). The words come from the country pages'
// content files, content/<slug>.id.json, under lineLabels (English -> Indonesian), so one
// translation serves the country page and the calculator; the template matching that lets
// one entry word every rate and every US state is labels-runtime.js.
//
//   node global-income-tax-calculator/_jurisdictions/labels.mjs           write labels-id.js
//   node global-income-tax-calculator/_jurisdictions/labels.mjs --check   write nothing; fail if it is stale
//
// A new or reworded engine label needs its Indonesian in that country's lineLabels: the check
// node global-income-tax-calculator/_audit/labels-id.mjs runs every country and option through
// the engine and fails on any text without it. Re-run this after editing a content file.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { PAGES } from './scenarios.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const TOOL = join(HERE, '..');
const require = createRequire(import.meta.url);
const E = require(join(TOOL, 'engine.js'));
const R = require(join(HERE, 'labels-runtime.js'));
const OUT = join(TOOL, 'labels-id.js');
const CHECK = process.argv.includes('--check');

// Names kept as they are inside a label, so one entry serves them all.
const NAMES = { US: Object.values(E.US_STATES) };
// A figure as Indonesian writes it: 1.234,5 for the calculator's 1,234.5.
const idForm = t => t.replace(/[.,]/g, c => c === ',' ? '.' : ',');
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const map = { '*': {} }, lit = { '*': {} }, problems = [], loose = [];
for(const p of PAGES){
  const f = join(HERE, 'content', `${p.slug}.id.json`);
  if(!existsSync(f)) continue;
  const labels = JSON.parse(readFileSync(f, 'utf8')).lineLabels || {};
  const cc = p.cc;
  map[cc] = {}; lit[cc] = {};
  for(const [en, raw] of Object.entries(labels)){
    const id = raw.replace(/<[^>]+>/g, '');   // the country pages may italicise a term; the calculator shows plain text
    if(/—/.test(id)) problems.push(`${p.slug}: an em-dash in "${id}"`);
    const pt = R.parts(en, NAMES[cc]);
    let tpl = id, ok = true;
    pt.nums.forEach((t, i) => {
      if(!ok) return;
      const hit = [idForm(t), t].map(form => new RegExp(`(?<![\\d.,{])${esc(form)}(?![\\d}]|[.,]\\d)`)).find(re => re.test(tpl));
      if(hit) tpl = tpl.replace(hit, `{${i}}`); else ok = false;
    });
    pt.names.forEach((n, i) => {
      if(!ok) return;
      if(tpl.includes(n)) tpl = tpl.replace(n, `{${'ABCDEFGH'[i]}}`); else ok = false;
    });
    // A figure the Indonesian wrote its own way (1.500.000, 0,5) reads as the calculator writes figures.
    tpl = tpl.replace(/\d{1,3}(?:\.\d{3})+(?:,\d+)?|\d+,\d+/g, m => /^\d+,\d{3}$/.test(m) && !/\./.test(m) ? m : idForm(m));
    if(!ok){ lit[cc][en] = tpl.replace(/\{(\d+|[A-H])\}/g, (m, k) => /\d/.test(k) ? pt.nums[+k] : pt.names['ABCDEFGH'.indexOf(k)]); loose.push(`${p.slug}: "${en}" -> "${id}" (a figure or name in the English is not in the Indonesian, so it matches only word for word)`); continue; }
    if(map[cc][pt.key] != null && map[cc][pt.key] !== tpl) problems.push(`${p.slug}: "${en}" gives "${tpl}", another label of the same shape gives "${map[cc][pt.key]}"`);
    else map[cc][pt.key] = tpl;
    if(map['*'][pt.key] == null) map['*'][pt.key] = tpl;
  }
}

const runtime = readFileSync(join(HERE, 'labels-runtime.js'), 'utf8').split('// @end-runtime')[0].replace(/^\/\*[\s\S]*?\*\/\n/, '');
const data = { names: NAMES, map, lit };
const js = `/* Generated by _jurisdictions/labels.mjs from _jurisdictions/content/<slug>.id.json (lineLabels):
   edit those, then run it. Loaded by the Indonesian page only (id/): window.GSCLabelsId.tr(text, country)
   is the Indonesian for a text the engine wrote, or null. How it matches: _jurisdictions/labels-runtime.js. */
(function(global){
${runtime.trim()}
var DATA = ${JSON.stringify(data)};
var api = { tr: gscLabelsRuntime().make(DATA), data: DATA };
if(typeof module !== 'undefined' && module.exports) module.exports = api;
else global.GSCLabelsId = api;
})(typeof window !== 'undefined' ? window : globalThis);
`;
if(loose.length) console.log(loose.map(s => '  note: ' + s).join('\n'));
if(problems.length){ console.error(problems.map(s => '  ' + s).join('\n')); process.exitCode = 1; }
const old = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if(old === js) console.log('labels-id.js is up to date.');
else if(CHECK){ console.error('out of date: global-income-tax-calculator/labels-id.js (run node global-income-tax-calculator/_jurisdictions/labels.mjs)'); process.exitCode = 1; }
else { writeFileSync(OUT, js); console.log('labels-id.js written.'); }
