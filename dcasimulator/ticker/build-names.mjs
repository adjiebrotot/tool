// Builds names.js from this folder's index.html: every row of the reference
// tables becomes TICKER → full name, so the simulators' asset pickers can find
// DHHF.AX by typing "Betashares". Names the market-data Worker returns for a
// loaded ticker win over these; this is the offline fallback for the common ones.
//
// Run after editing the tables: node dcasimulator/ticker/build-names.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const html = readFileSync(here + 'index.html', 'utf8');
const decode = s => s.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, ' ').trim();
const names = {};
const row = /<td class="tk">([\s\S]*?)<\/td>[\s\S]*?<td class="nm">([\s\S]*?)<\/td>/g;
let m;
while ((m = row.exec(html))) {
  const tk = decode(m[1]).toUpperCase(), nm = decode(m[2]);
  if (tk && nm && !names[tk]) names[tk] = nm;
}
const body = Object.keys(names).sort().map(k => '  ' + JSON.stringify(k) + ':' + JSON.stringify(names[k])).join(',\n');
writeFileSync(here + 'names.js',
`/* Generated by build-names.mjs from index.html - edit the tables there, then rerun it.
   Full names of the reference tickers, for the simulators' asset pickers. */
window.DCA_TICKER_NAMES = {
${body}
};
`);
console.log(Object.keys(names).length + ' ticker names written to names.js');
